module Table1Reporting

using CSV
using DataFrames
using PrettyTables
using Printf
using Statistics

export aggregate_table1

"""
    aggregate_table1(paths, prefix; require_full::Bool=true, stat::Symbol=:min, time_unit::Symbol=:ms, show_table::Bool=true)

Validates raw benchmark CSV files generated by `run_experiments.jl` and computes:
1. Per-instance timing statistic across `BenchmarkTools` samples (`stat = :min` for `@belapsed` minimum time, or `stat = :median` for median time).
2. Arithmetic mean across the three coherence levels `c in {0.0, 0.1, 0.2}` for each `(rows, columns)` configuration.
3. Outputs:
   - `\$(prefix)_instances.csv`: per-instance summary.
   - `\$(prefix).csv`: configuration means (with both `time_min_seconds`, `time_median_seconds`, and selected `time_seconds`).
   - `\$(prefix).tex`: publication-ready LaTeX table with boldface highlights (`\\textbf{...}`) for best Iterations, Projections, and Time per configuration.
   - `\$(prefix)_assessment.txt`: automated win/tie counts comparing P-CRM, CRM, and F-SPM.
"""
function aggregate_table1(
    paths::AbstractVector{<:AbstractString},
    prefix::AbstractString;
    require_full::Bool = true,
    stat::Symbol = :min,
    time_unit::Symbol = :ms,
    show_table::Bool = true
)
    isempty(paths) && error("Supply at least one raw CSV file")
    stat in (:min, :median, :mean) || error("Invalid timing statistic: $stat (expected :min, :median, or :mean)")
    time_unit in (:ms, :s) || error("Invalid time_unit: $time_unit (expected :ms or :s)")

    raw = reduce(vcat, CSV.read.(paths, DataFrame))
    nrow(raw) > 0 || error("Empty raw data")

    for col in [:source_sha256, :seed, :tolerance, :iteration_limit, :blas_threads,
                :julia_version, :mode, :environment_sha256, :repetitions]
        if col in propertynames(raw)
            length(unique(raw[!, col])) == 1 || error("Mixed $col in the input files")
        end
    end

    key = [:method, :threads, :blocks, :rows, :columns, :coherence]
    repetition_key = vcat(key, [:repetition])
    nrow(unique(raw, repetition_key)) == nrow(raw) || error("Duplicate timing samples")

    for g in groupby(raw, key)
        sort(g.repetition) == collect(1:only(unique(g.repetitions))) || error("Missing timing samples")
        for col in [:iterations, :projections, :instance_sha256, :converged, :status]
            length(unique(g[!, col])) == 1 || error("Inconsistent repetitions: $col")
        end
        all(g.projections .== g.iterations .* g.blocks) || error("Incorrect counters")
        all(g.converged .== (isfinite.(g.relative_error) .& (g.relative_error .<= g.tolerance))) ||
            error("Convergence flags do not match the measured error")
    end

    for g in groupby(raw, [:rows, :columns, :coherence])
        length(unique(g.instance_sha256)) == 1 || error("Methods used different instances/partitions")
    end

    stat_fn = stat == :min ? minimum : (stat == :median ? median : mean)

    instances = combine(groupby(raw, key),
        :iterations => first => :iterations,
        :projections => first => :projections,
        :time_seconds => stat_fn => :time_seconds,
        :time_seconds => minimum => :time_min_seconds,
        :time_seconds => median => :time_median_seconds,
        :relative_error => maximum => :relative_error,
        :converged => all => :converged
    )

    if require_full
        only(unique(raw.mode)) == "full" || error("Smoke results are not publication results")
        worker_counts = sort(filter(>(1), unique(raw.threads)))
        isempty(worker_counts) && error("Supply at least one serial run (threads=1) and one multithreaded run (threads>1)")
        expected = Set{Tuple{String,Int}}([
            ("CRM", 1),
            ("P-CRM", 1),
            ("F-SPM (uniform weights)", 1)
        ])
        for nt in worker_counts
            push!(expected, ("P-CRM", nt))
            push!(expected, ("F-SPM (uniform weights)", nt))
        end
        sizes = Set((m, n) for m in [5000, 7500, 10000, 12500] for n in [100, 250, 500])
        Set(zip(raw.rows, raw.columns)) == sizes || error("Incomplete problem-size grid")
        for g in groupby(instances, [:rows, :columns])
            Set(zip(g.method, g.threads)) == expected || error("Missing method/thread variant")
            for variant in groupby(g, [:method, :threads])
                sort(variant.coherence) == [0.0, 0.1, 0.2] || error("Missing coherence levels")
            end
        end
    end

    summary = combine(groupby(instances, key[1:5]),
        :iterations => mean => :iterations,
        :projections => mean => :projections,
        :time_seconds => mean => :time_seconds,
        :time_min_seconds => mean => :time_min_seconds,
        :time_median_seconds => mean => :time_median_seconds,
        :converged => (x -> count(!, x)) => :failed_instances,
        nrow => :instances
    )
    sort!(summary, [:blocks, :rows, :columns, :method, :threads])

    mkpath(dirname(abspath(prefix)))
    CSV.write(prefix * "_instances.csv", instances)
    CSV.write(prefix * ".csv", summary)

    # Determine best (minimum) values per (rows, columns) group for LaTeX bold highlighting
    best_iter = Dict{Tuple{Int,Int}, Float64}()
    best_proj = Dict{Tuple{Int,Int}, Float64}()
    best_time = Dict{Tuple{Int,Int}, Float64}()
    for g in groupby(summary, [:rows, :columns])
        valid = g[g.failed_instances .== 0, :]
        if nrow(valid) > 0
            sk = (g.rows[1], g.columns[1])
            best_iter[sk] = minimum(valid.iterations)
            best_proj[sk] = minimum(valid.projections)
            best_time[sk] = minimum(valid.time_seconds)
        end
    end

    stat_desc = stat == :min ? "minimum (BenchmarkTools @belapsed)" : (stat == :median ? "median" : "mean")
    unit_label = time_unit == :ms ? "Time (ms)" : "Time (s)"
    scale = time_unit == :ms ? 1e3 : 1.0

    open(prefix * ".tex", "w") do io
        println(io, "% Generated from: ", join(basename.(paths), ", "))
        println(io, "% Time: mean across coherence levels of per-instance $stat_desc solve times.")
        println(io, "% * means one or more instances did not reach tolerance.")
        println(io, "\\begin{tabular}{lrrrrrrr}\n\\toprule")
        println(io, "Method & Threads & Blocks & Rows & Columns & Iterations & Projections & $unit_label \\\\")
        println(io, "\\midrule")
        last_size = nothing
        for r in eachrow(summary)
            size_key = (r.rows, r.columns)
            !isnothing(last_size) && last_size != size_key && println(io, "\\midrule")
            flag = r.failed_instances > 0 ? "\\textsuperscript{*}" : ""

            it_str = @sprintf("%.2f", r.iterations)
            pr_str = @sprintf("%.2f", r.projections)
            tm_str = time_unit == :ms ? @sprintf("%.3f", r.time_seconds * scale) : @sprintf("%.6f", r.time_seconds)

            if r.failed_instances == 0 && haskey(best_iter, size_key)
                isapprox(r.iterations, best_iter[size_key]; atol=1e-9) && (it_str = "\\textbf{$it_str}")
                isapprox(r.projections, best_proj[size_key]; atol=1e-9) && (pr_str = "\\textbf{$pr_str}")
                isapprox(r.time_seconds, best_time[size_key]; rtol=1e-12, atol=1e-12) && (tm_str = "\\textbf{$tm_str}")
            end

            @printf(io, "%s%s & %d & %d & %d & %d & %s & %s & %s \\\\\n",
                    r.method, flag, r.threads, r.blocks, r.rows, r.columns,
                    it_str, pr_str, tm_str)
            last_size = size_key
        end
        println(io, "\\bottomrule\n\\end{tabular}")
    end

    open(prefix * "_assessment.txt", "w") do io
        println(io, "Counts below compare configuration means using full precision (per-instance statistic: $stat_desc).")
        for nt in sort(unique(summary[summary.method .== "P-CRM", :threads]))
            pairs = crm_faster = pcrm_faster = equal = more = fewer = excluded = 0
            fspm_pairs = pcrm_beats_fspm_time = pcrm_beats_fspm_proj = 0
            for g in groupby(summary, [:rows, :columns])
                c = g[(g.method .== "CRM") .& (g.threads .== 1), :]
                p = g[(g.method .== "P-CRM") .& (g.threads .== nt), :]
                f = g[(g.method .== "F-SPM (uniform weights)") .& (g.threads .== nt), :]
                if nrow(c) == 1 && nrow(p) == 1
                    if c.failed_instances[1] + p.failed_instances[1] > 0
                        excluded += 1
                    else
                        pairs += 1
                        crm_faster += c.time_seconds[1] < p.time_seconds[1]
                        pcrm_faster += p.time_seconds[1] < c.time_seconds[1]
                        delta = p.projections[1] - c.projections[1]
                        equal += isapprox(delta, 0.0; atol=1e-9)
                        more += delta > 1e-9
                        fewer += delta < -1e-9
                    end
                end
                if nrow(p) == 1 && nrow(f) == 1 && (p.failed_instances[1] + f.failed_instances[1] == 0)
                    fspm_pairs += 1
                    pcrm_beats_fspm_time += p.time_seconds[1] < f.time_seconds[1]
                    pcrm_beats_fspm_proj += p.projections[1] < f.projections[1]
                end
            end
            println(io, "P-CRM threads=$nt vs CRM (threads=1): configurations=$pairs; CRM faster=$crm_faster; P-CRM faster=$pcrm_faster; P-CRM projections equal=$equal, greater=$more, fewer=$fewer; failed pairs excluded=$excluded.")
            if fspm_pairs > 0
                println(io, "P-CRM threads=$nt vs F-SPM threads=$nt: configurations=$fspm_pairs; P-CRM faster=$pcrm_beats_fspm_time; P-CRM fewer projections=$pcrm_beats_fspm_proj.")
            end
        end
        println(io, "Failed method/configuration groups: ", count(>(0), summary.failed_instances))
    end

    if show_table
        display_df = copy(summary)
        display_df[!, :time_ms] = round.(display_df.time_seconds .* 1e3; digits=3)
        display_df[!, :iterations] = round.(display_df.iterations; digits=2)
        display_df[!, :projections] = round.(display_df.projections; digits=2)
        select!(display_df, [:method, :threads, :blocks, :rows, :columns, :iterations, :projections, :time_ms, :failed_instances])
        pretty_table(display_df)
    end

    return summary
end

end # module Table1Reporting

if abspath(PROGRAM_FILE) == (@__FILE__)
    stat_opt = :min
    unit_opt = :ms
    positional = String[]
    for arg in ARGS
        if startswith(arg, "--stat=")
            stat_opt = Symbol(split(arg, '='; limit=2)[2])
        elseif startswith(arg, "--unit=")
            unit_opt = Symbol(split(arg, '='; limit=2)[2])
        else
            push!(positional, arg)
        end
    end

    if isempty(positional)
        default_dir = joinpath(dirname(@__DIR__), "data", "table1")
        csv_files = sort(filter(f -> startswith(basename(f), "raw_threads") && endswith(f, ".csv"), readdir(default_dir; join=true)))
        isempty(csv_files) && error("Usage: julia --project=. scripts/make_table1.jl [--stat=min|median] [--unit=ms|s] [OUTPUT_PREFIX RAW_THREADS1.csv RAW_THREADSN.csv...]")
        prefix = joinpath(default_dir, "table1")
        Table1Reporting.aggregate_table1(csv_files, prefix; stat=stat_opt, time_unit=unit_opt)
        println("Generated ", prefix, ".csv, .tex, _instances.csv and _assessment.txt")
    else
        length(positional) >= 2 || error("Usage: OUTPUT_PREFIX RAW_THREADS1.csv [RAW_THREADSN.csv...]")
        require_full = length(positional) >= 3
        Table1Reporting.aggregate_table1(positional[2:end], positional[1]; require_full=require_full, stat=stat_opt, time_unit=unit_opt)
        println("Generated ", positional[1], ".csv, .tex, _instances.csv and _assessment.txt")
    end
end
